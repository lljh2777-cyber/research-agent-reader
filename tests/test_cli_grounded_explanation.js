const assert=require("node:assert/strict");
const {loadReading}=require("./reading-test-helpers");
const {renderCliGroundedExplanation:render}=loadReading("annotations/cli-grounded-explanation.ts");
const {AnnotationService}=loadReading("annotations/annotation-service.ts");
const pair=(quote,meaning,extra={})=>JSON.stringify({claims:[{quote,meaning}],...extra});
const association="Subtype A had 6/25 cases compared with 1/71 in other subtypes (P = 0.0011, Fisher's exact test).";
const purpose="We selected samples with epithelial content ≥40% to balance stromal gene expression.";
assert.throws(()=>render(pair(association,"表明两者存在较强的关联。"),association),/关联强弱/);
assert.throws(()=>render(pair(association,"这属于很大的效应。"),association),/效应大小/);
assert.doesNotThrow(()=>render(pair(association,"作者报告 6/25 与 1/71 的分布差异；P 值不提供关联强弱判断。"),association));
assert.doesNotThrow(()=>render(pair("A strong association was reported.","作者报告了强关联。"),"A strong association was reported."));
assert.throws(()=>render(pair("No strong association was reported.","作者报告了强关联。"),"No strong association was reported."),/关联强弱/);
assert.throws(()=>render(pair(purpose,"提高上皮含量门槛可使各类样本间间质来源表达的差异相对均衡，减少其对分型的干扰。"),purpose),/阈值作用/);
assert.throws(()=>render(pair(purpose,"≥40% 上皮含量让上皮与间质的比例均衡。"),purpose),/比例均衡/);
assert.doesNotThrow(()=>render(pair(purpose,"作者选择上皮含量 ≥40% 的样本，目的为平衡间质基因表达。"),purpose));
assert.doesNotThrow(()=>render(pair(purpose,"该段不能据此断言上皮与间质的比例均衡。"),purpose));
const effect="Raising the epithelial-content threshold reduced stromal variation.";
assert.doesNotThrow(()=>render(pair(effect,"作者报告提高上皮含量门槛减少了间质表达差异。"),effect));
const ratio="Epithelial and stromal cells had equal proportions.";
assert.doesNotThrow(()=>render(pair(ratio,"作者报告上皮与间质细胞的比例相等。"),ratio));
assert.throws(()=>render(pair(purpose,"作者报告已减少干扰。",{background:"可推演门槛的作用"}),purpose),/额外背景字段/);
assert.throws(()=>render(pair("We purified the tumour cells.","作者纯化细胞。"),purpose),/引句不在/);
assert.throws(()=>render(pair(association,"两组存在差异。"),association+"\n"+purpose,undefined,"epithelial content"),/未覆盖/);
assert.throws(()=>render(pair("两组存在差异。","两组存在差异。"),association,"zh-CN","两组存在差异。"),/引句不在/);
assert.throws(()=>render(pair(purpose,"一般知识／解释性推断：提高门槛减少干扰。"),purpose),/背景推演/);
assert.throws(()=>render(JSON.stringify({claims:[]}),purpose));
const multiline="RNA-seq\r\nresolved four classes.";
assert.match(render(pair(multiline.replace(/\r/g,""),"作者报告四个类别。"),multiline),/> RNA-seq\n> resolved/);
assert.match(render(pair(association,"作者报告两组分布差异。"),association,"zh-CN"),/^译文对照：.*仍待人工核对。\n\n英文依据：/);
assert.throws(()=>render(pair(association,"两组存在差异。",{translationCheck:"译文一致"}),association));
(async()=>{
 let calls=0;
 const cli={generate:async()=>{calls++;return {text:pair(association,"存在较强的关联。"),requestedModel:"Qwen3.8-Flash"};}};
 const service=new AnnotationService({}, {settings:{annotationBackendId:"qoderclicn",annotationQoderModel:"Qwen3.8-Flash",annotationCliTimeoutSeconds:120}},cli);
 await assert.rejects(service.generateExplanation({sourcePath:"papers/fixture.md",selectedText:"6/25",context:association},()=>{}),/关联强弱/);
 assert.equal(calls,1,"reject unsupported meaning without retrying or changing model");
 console.log("CLI_GROUNDED_EXPLANATION_OK (old failures, source-supported counterexamples, quote fidelity, role schema, one-call rejection)");
})().catch(error=>{console.error(error);process.exitCode=1;});
