/* Run explicitly through Obsidian CLI eval. Creates labelled demo sessions only;
 * never calls a model, exports a note, or deletes any file. Not a Node unit test. */
module.exports = async function readingUiScenario(app) {
	const check = (value, label) => { if (!value) throw new Error(label); };
	const pause = (ms = 100) => new Promise((resolve) => require("node:timers").setTimeout(resolve, ms));
	const plugin = app.plugins.plugins["research-agent-reader"];
	await plugin.activateReadingWorkspace();
	const workspace = plugin.getReadingWorkspace(); const id = await workspace.demo();
	const view = app.workspace.getLeavesOfType("research-interactive-reading")[0].view;
	await workspace.repository.transact(id, (s) => { s.title = "集成验收 · 双模式与分支（示例）"; });
	await view.setState({ sessionId: id });
	const root = view.contentEl; const session = () => workspace.repository.get(id);
	const settle = async () => { await pause(); await workspace.repository.flush(); await pause(); };
	const click = (parent, label) => { const b = [...parent.querySelectorAll("button")].find((b) => b.textContent === label); check(b, "button " + label); b.click(); };
	const type = (input, value) => { check(input, "input exists"); input.value = value; input.dispatchEvent(new Event("input", { bubbles: true })); };
	const mainInput = () => root.querySelector("textarea[data-composer^='main:']");
	await settle(); check(root.querySelectorAll(".reading-map-node").length === 4, "initial graph");
	const first = session().mainIds[0]; const second = session().mainIds[1];
	view.selectNode(first); await settle(); type(mainInput(), "第一个节点的草稿");
	view.selectNode(second); await settle(); type(mainInput(), "第二个节点的草稿");
	view.selectNode(first); await settle(); check(mainInput().value === "第一个节点的草稿", "draft isolation");
	const branchId = session().branches[0].id; const branchNode = session().branches[0].nodeIds[0];
	view.selectNode(branchNode); await settle(); check(mainInput().dataset.composer === "main:" + first, "branch keeps main input target");
	let floating = root.querySelector(".reading-float"); check(floating, "branch popup");
	type(floating.querySelector("textarea"), "继续这条示例支线"); click(floating, "发送"); click(floating, "发送"); await settle();
	check(session().branches.find((b) => b.id === branchId).nodeIds.length === 2, "continue branch and deduplicate send");
	floating = root.querySelector(".reading-float"); click(floating, "固定"); await settle();
	click(root, "仅思维导图"); await settle(); check(!root.querySelector(".reading-main-chat"), "map only");
	view.selectNode(first); await settle(); check(root.querySelectorAll(".reading-float").length === 2, "pinned window survives navigation");
	floating = [...root.querySelectorAll(".reading-float")].find((w) => w.dataset.windowKey === first);
	const header = floating.querySelector(".reading-float-header"); const bounds = header.getBoundingClientRect();
	header.dispatchEvent(new PointerEvent("pointerdown", { bubbles: true, clientX: bounds.x + 15, clientY: bounds.y + 15 }));
	document.dispatchEvent(new PointerEvent("pointermove", { clientX: bounds.x + 135, clientY: bounds.y + 95 }));
	document.dispatchEvent(new PointerEvent("pointerup")); await settle();
	check(session().ui.windows.find((w) => w.key === first).x > 100, "window drag persisted");
	floating = [...root.querySelectorAll(".reading-float")].find((w) => w.dataset.windowKey === first);
	const resize = floating.querySelector(".reading-resize"); const box = floating.getBoundingClientRect();
	resize.dispatchEvent(new PointerEvent("pointerdown", { bubbles: true, clientX: box.right, clientY: box.bottom }));
	document.dispatchEvent(new PointerEvent("pointermove", { clientX: box.left + 580, clientY: box.top + 540 })); document.dispatchEvent(new PointerEvent("pointerup")); await settle();
	check(session().ui.windows.find((w) => w.key === first).width === 580, "resize persisted");
	floating = [...root.querySelectorAll(".reading-float")].find((w) => w.dataset.windowKey === first); click(floating, "收起"); await settle();
	check(session().ui.windows.find((w) => w.key === first).minimized, "minimize");
	floating = [...root.querySelectorAll(".reading-float")].find((w) => w.dataset.windowKey === first); click(floating, "展开"); await settle();
	view.selectNode(branchNode); await settle();
	const answer = [...root.querySelectorAll(".reading-float [data-answer-id]")].find((n) => n.dataset.answerId === branchNode);
	const content = answer.querySelector(".reading-answer-content");
	const walker = document.createTreeWalker(content, NodeFilter.SHOW_TEXT); let textNode;
	while ((textNode = walker.nextNode()) && textNode.textContent.length < 10) {}
	check(textNode, "rendered quote text"); const range = document.createRange(); range.setStart(textNode, 0); range.setEnd(textNode, 10);
	const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range);
	content.dispatchEvent(new MouseEvent("mouseup", { bubbles: true })); await settle();
	check(session().ui.pendingQuote?.nodeId === branchNode, "selection quote persisted");
	floating = [...root.querySelectorAll(".reading-float")].find((w) => w.dataset.windowKey === branchId);
	type(floating.querySelector("textarea"), "解释选中的内容"); click(floating, "发送"); await settle();
	const child = session().branches.at(-1); check(child.parentNodeId === branchNode, "child branch anchor");
	check(session().nodes.find((n) => n.id === child.nodeIds[0]).quote?.nodeId === branchNode, "child quote");
	click(root, "导图＋对话"); await settle(); check(root.querySelectorAll(".reading-main-chat .reading-answer").length === 3, "main transcript unchanged");
	await pause(500); await workspace.repository.flush();
	const saved = JSON.parse(await workspace.repository.storage.read(id));
	check(saved.ui.drafts["main:" + first] === "第一个节点的草稿", "draft on disk");
	check(saved.ui.windows.some((w) => w.pinned), "pinned on disk");
	return { status: "passed", sessionId: id, nodes: saved.nodes.length, branches: saved.branches.length,
		checks: ["mode switch", "main jump", "input target", "draft isolation", "branch continuation", "double send", "pin", "drag", "resize", "minimize", "selection child", "persistence"] };
};
